#!/usr/bin/env node
'use strict';
// ════════════════════════════════════════════════════════════════
// rsf-wizard-ui-check — the REAL ERP page in a REAL Chrome (not API calls), at a custom port: the Rashid bootstrap wizard on /login
// (choose the .rsf, admin account form, «إنشاء ومتابعة إلى المعاينة») must reach the data preview.
//
// Field bug (2.0.0, a Windows Server PC upgraded from 1.x): the wizard failed with the DEVELOPER text of src/lib/localDevApi.ts
// ("VITE_TEXACORE_LOCAL_API_SECRET is not set… npm run dev:local"): the page had not received the installer's admin secret in /config.js.
// Mechanism found: the web bundle's service worker precached /config.js under a revision that never changes, so the first copy it ever stored (an older install's,
// without the admin bits) was served to the page for good. This check makes the cached-stale situation real and requires the wizard to still work.
//
//   H1  the headers: /config.js no-store + Pragma; the shell no-cache and its config script versioned (?v=); hashed assets immutable; the served sw.js has no config.js precache entry
//   S1  a clean profile, the normal path
//   S2  a profile with a service worker whose precache holds a STALE 1.x-style /config.js (no admin bits, old key) → the app restarts ("the upgrade") → the wizard works
//   S3  an intermediary that ignores the cache-busting query and answers the page's /config.js with the stale copy, plus a local "security product" adding Via / X-Forwarded-For: 127.0.0.1
//       → the page asks for a fresh copy once (ERP localDevApi) and the wizard works
//   S4  tunnel-shaped requests (Cf-Ray, Cf-Connecting-Ip, Cdn-Loop, X-Forwarded-For: <foreign>) get NO admin bits, and the wizard says the FRIENDLY localized text — never developer words
//
//   node scripts/e2e/rsf-wizard-ui-check.js --workdir <empty dir> --erp <ERP checkout with node_modules/playwright> --rsf <file.rsf> [--app <packaged .app>]
// ════════════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
const http = require('http');
const { PORTS, Results, portFree, startApp, stopApp, request } = require('./lib');

const arg = (n, d = '') => { const i = process.argv.indexOf(`--${n}`); return i >= 0 ? process.argv[i + 1] : d; };
const WORK = path.resolve(arg('workdir', ''));
const ERP = path.resolve(arg('erp', process.env.TEXACORE_ERP_DIR || ''));
const RSF = arg('rsf', '');
const APP = arg('app', '');
if (!arg('workdir') || !arg('erp') || !RSF) { console.error('--workdir, --erp and --rsf are required'); process.exit(2); }
const binary = APP ? path.join(path.resolve(APP), 'Contents', 'MacOS', path.basename(path.resolve(APP), '.app')) : '';
const { chromium } = require(path.join(ERP, 'node_modules', 'playwright'));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const UI = `http://localhost:${PORTS.ui}`;               // not 80 / 8080: a custom port, as on the owner's machines

// a 1.x-style config.js: the old public anon key, no admin bits (what an older install's server answered)
const STALE_CONFIG_JS = `// Auto-generated by TexaCore Service Manager
window.__TEXACORE_CONFIG__ = {
  supabaseUrl: "http://localhost:54321",
  supabaseKey: "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1sb2NhbCIsInJlZiI6InRleGFjb3JlLWxvY2FsIiwicm9sZSI6ImFub24iLCJpYXQiOjE3MDAwMDAwMDAsImV4cCI6MjU0MDAwMDAwMH0.OLD-1X-KEY",
  mode: "selfhosted",
  appVersion: "1.8.0",
  VITE_SUPABASE_URL: "http://localhost:54321"
};
`;

const PREVIEW_RE = /معاينة البيانات|Data preview|Предпросмотр данных|Перегляд даних/;
const FRIENDLY_RE = /تعذّر الوصول إلى خدمة الإدارة المحلية|The local administration service could not be reached|Не удалось связаться с локальной службой|Не вдалося зв’язатися з локальною службою/;
const DEV_TEXT_RE = /VITE_TEXACORE_LOCAL_API_SECRET|npm run dev:local|TEXACORE_LOCAL_API_SECRET/;

async function overlayText(page) {
  return page.evaluate(() => { const el = [...document.querySelectorAll('div.fixed.inset-0')].find((e) => /z-\[100\]/.test(e.className)); return el ? el.innerText : null; });
}

/** Drives the wizard on /login of `page`; resolves { reached, preview, error }. */
async function runWizard(page, { email, expectFailure = false, shots, shot }) {
  await page.goto(`${UI}/login`, { waitUntil: 'networkidle', timeout: 120000 });
  const cfg = await page.evaluate(() => ({ secret: !!(window.__TEXACORE_CONFIG__ && window.__TEXACORE_CONFIG__.localApiSecret), keys: Object.keys(window.__TEXACORE_CONFIG__ || {}), version: window.__TEXACORE_CONFIG__ && window.__TEXACORE_CONFIG__.appVersion }));
  await page.locator('#company-file-upload').setInputFiles(RSF);
  await page.waitForSelector('input[type="email"]', { timeout: 60000 });
  await page.waitForTimeout(3500);                                           // the file's currencies are read in the browser first
  await page.locator('input[type="email"]').fill(email);
  await page.locator('input[type="password"]').fill('RsfPass#2026');
  await page.getByRole('button', { name: /Create & continue to preview|إنشاء ومتابعة إلى المعاينة|Создать и перейти|Створити й перейти/ }).click();
  const t0 = Date.now();
  let overlay = null; let error = null;
  while (Date.now() - t0 < (expectFailure ? 25000 : 120000)) {
    await page.waitForTimeout(1500);
    overlay = await overlayText(page);
    if (overlay && PREVIEW_RE.test(overlay)) break;
    error = await page.evaluate(() => { const e = [...document.querySelectorAll('p,div,span')].find((x) => /text-red|destructive/.test(x.className || '') && (x.innerText || '').length > 15 && x.children.length === 0); return e ? e.innerText : null; });
    if (error && expectFailure) break;
    overlay = null;
  }
  if (shot && shots) await page.screenshot({ path: path.join(shots, shot) }).catch(() => {});
  return { cfg, reached: !!(overlay && PREVIEW_RE.test(overlay)), preview: overlay ? overlay.split('\n').join(' | ').slice(0, 260) : null, error, pageText: error ? null : (await page.evaluate(() => document.body.innerText)).slice(0, 400) };
}

const get = (url, headers = {}) => new Promise((resolve, reject) => {
  http.get(url, { headers }, (res) => { let b = ''; res.on('data', (c) => { b += c; }); res.on('end', () => resolve({ status: res.statusCode, headers: res.headers, body: b })); }).on('error', reject);
});

(async () => {
  const R = new Results();
  fs.rmSync(WORK, { recursive: true, force: true }); fs.mkdirSync(WORK, { recursive: true });
  const shots = path.join(WORK, 'shots'); fs.mkdirSync(shots, { recursive: true });
  for (const p of Object.values(PORTS)) if (!(await portFree(p))) { console.error(`port ${p} busy`); process.exit(2); }
  if (!fs.existsSync(RSF)) { console.error(`rsf file not found: ${RSF}`); process.exit(2); }
  const userData = path.join(WORK, 'userdata');
  const evidence = {};
  const boot = (tag) => startApp({ userData, license: 'trial', logFile: path.join(WORK, `app-${tag}.log`), appBinary: binary });
  const hb = () => { try { return fs.readFileSync(path.join(userData, 'texacore-data', 'logs', 'heartbeat.log'), 'utf8'); } catch { return ''; } };
  const bundleDir = APP ? path.join(path.resolve(APP), 'Contents', 'Resources', 'frontend') : path.join(__dirname, '..', '..', 'frontend');

  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  let { child, ready } = boot('1');
  try {
    await ready;

    // ── H1 headers ──
    await R.check('H1 /config.js is no-store; the shell is no-cache with a VERSIONED config script; hashed assets are immutable; the served service worker has no config.js precache entry', async () => {
      const cfgJs = await get(`${UI}/config.js`);
      const cc = String(cfgJs.headers['cache-control'] || '');
      if (!/no-store/.test(cc) || !/max-age=0/.test(cc) || !/no-cache/i.test(String(cfgJs.headers.pragma || ''))) throw new Error(`/config.js: Cache-Control "${cc}", Pragma "${cfgJs.headers.pragma}"`);
      const shell = await get(`${UI}/login`);
      if (!/no-cache|no-store/.test(String(shell.headers['cache-control'] || ''))) throw new Error(`shell Cache-Control "${shell.headers['cache-control']}"`);
      const m = /<script[^>]*src="(\/config\.js\?v=[^"]+)"/.exec(shell.body);
      if (!m) throw new Error('the shell\'s config script is not versioned');
      const root = await get(`${UI}/`);
      if (!root.body.includes(m[1].split('?')[0] + '?v=')) throw new Error('/ is not versioned');
      const a = /assets\/[A-Za-z0-9_.-]+\.js/.exec(shell.body);
      let assetCc = '(no asset in the shell)';
      if (a) { const asset = await get(`${UI}/${a[0]}`); assetCc = String(asset.headers['cache-control'] || ''); if (!/immutable/.test(assetCc)) throw new Error(`asset ${a[0]}: Cache-Control "${assetCc}"`); }
      const sw = await get(`${UI}/sw.js`);
      if (/url:\s*["']config\.js["']/.test(sw.body)) throw new Error('the served sw.js still precaches config.js');
      if (!/no-cache|no-store/.test(String(sw.headers['cache-control'] || ''))) throw new Error('sw.js is cacheable');
      const versioned = await get(`${UI}${m[1]}`);
      if (!/localApiSecret/.test(versioned.body)) throw new Error('the versioned config.js has no admin bits for a local request');
      evidence.headers = { config: cc, shell: shell.headers['cache-control'], script: m[1], asset: assetCc, sw: sw.headers['cache-control'] };
      return `/config.js "${cc}" + Pragma no-cache; shell "${shell.headers['cache-control']}", script ${m[1]}; asset "${assetCc}"; sw.js without the config.js entry`;
    });

    // ── S1 ──
    await R.check('S1 clean profile, custom port: the wizard reaches the data preview', async () => {
      const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
      try {
        const r = await runWizard(await ctx.newPage(), { email: 'owner1@rsf.test', shots, shot: 'S1-preview.png' });
        if (!r.cfg.secret) throw new Error(`the page got no admin secret (config keys: ${r.cfg.keys})`);
        if (!r.reached) throw new Error(`no preview; error "${r.error}"; page "${r.pageText}"`);
        evidence.S1 = r; return `preview reached at ${UI}: ${r.preview.slice(0, 120)}…`;
      } finally { await ctx.close(); }
    });

    // ── S2 part 1: a profile that holds a stale precache from an "older install" ──
    const profile = path.join(WORK, 'chrome-profile');
    await R.check('S2a a profile whose service worker precache holds a STALE 1.x-style /config.js: the stale copy is really what the page gets for the bare path (control)', async () => {
      const ctx = await chromium.launchPersistentContext(profile, { channel: 'chrome', headless: true, viewport: { width: 1440, height: 1000 } });
      try {
        const page = ctx.pages()[0] || await ctx.newPage();
        // the OLD web bundle's service worker (precaches config.js), installed over the old server
        let oldSw = fs.readFileSync(path.join(bundleDir, 'sw.js'), 'utf8');
        // a bundle built with the ERP's own `globIgnores: ['**/config.js']` no longer lists the file: put the entry back to be the OLD bundle's worker
        if (!/url:\s*["']config\.js["']/.test(oldSw)) oldSw = oldSw.replace(/precacheAndRoute\(\[/, 'precacheAndRoute([{url:"config.js",revision:"59c4552ffff1d98f1d129fe0c22a39d8"},');
        if (!/url:\s*["']config\.js["']/.test(oldSw)) throw new Error('could not build an old-style service worker from the bundle\'s sw.js');
        await page.route((u) => u.pathname === '/sw.js', (route) => route.fulfill({ status: 200, contentType: 'application/javascript', headers: { 'cache-control': 'no-store' }, body: oldSw }));
        await page.goto(`${UI}/login`, { waitUntil: 'networkidle', timeout: 120000 });
        await page.evaluate(async () => { await navigator.serviceWorker.register('/sw.js', { scope: '/' }); await navigator.serviceWorker.ready; });
        await page.waitForTimeout(4000);
        // an older install's copy of /config.js sits in the precache now (same revision as the new bundle's: it is never refreshed)
        const seeded = await page.evaluate(async (stale) => {
          const names = (await caches.keys()).filter((n) => /precache/i.test(n));
          let n = 0;
          for (const name of names) { const c = await caches.open(name); for (const req of await c.keys()) if (/\/config\.js(\?|$)/.test(req.url)) { await c.put(req, new Response(stale, { headers: { 'content-type': 'application/javascript' } })); n++; } }
          return { caches: names, entries: n };
        }, STALE_CONFIG_JS);
        if (!seeded.entries) throw new Error(`no config.js entry in the precache to make stale (${JSON.stringify(seeded)})`);
        const viaSw = await page.evaluate(async () => { const t = await (await fetch('/config.js')).text(); return { len: t.length, secret: /localApiSecret/.test(t), old: /1\.8\.0/.test(t) }; });
        if (viaSw.secret || !viaSw.old) throw new Error(`the stale precache is not what the page gets: ${JSON.stringify(viaSw)}`);
        evidence.S2seed = { seeded, viaSw };
        return `old-bundle worker installed; precache entry replaced by a 1.x config (${viaSw.len} bytes, no admin bits) — a bare /config.js is answered with it`;
      } finally { await ctx.close(); }
    });

    // ── the "upgrade": the app restarts (new boot) ──
    await stopApp(child, userData);
    await sleep(2000);
    ({ child, ready } = boot('2'));
    await ready;

    await R.check('S2b after the upgrade (a new boot of the app) the SAME profile still has the old worker and the stale precache — and the wizard works', async () => {
      const ctx = await chromium.launchPersistentContext(profile, { channel: 'chrome', headless: true, viewport: { width: 1440, height: 1000 } });
      try {
        const page = ctx.pages()[0] || await ctx.newPage();
        const state = await (async () => { await page.goto(`${UI}/login`, { waitUntil: 'domcontentloaded', timeout: 120000 }); return page.evaluate(async () => ({ controller: !!navigator.serviceWorker.controller, regs: (await navigator.serviceWorker.getRegistrations()).length })); })();
        const r = await runWizard(page, { email: 'owner2@rsf.test', shots, shot: 'S2-preview.png' });
        if (!r.cfg.secret) throw new Error(`the page got no admin secret although the shell is versioned (config keys ${r.cfg.keys}; ${JSON.stringify(state)})`);
        if (!r.reached) throw new Error(`no preview; error "${r.error}"; page "${r.pageText}"`);
        evidence.S2 = { state, ...r };
        return `old worker ${state.controller ? 'controlling' : 'registered'}${state.regs ? '' : ' (none left)'}, stale precache present; the page still got the admin secret; preview reached: ${r.preview.slice(0, 100)}…`;
      } finally { await ctx.close(); }
    });

    // ── S3: an intermediary that ignores the query AND a local security product's headers ──
    await R.check('S3 a cache that answers the versioned /config.js with the stale copy + a local product adding Via / X-Forwarded-For: 127.0.0.1: the page asks once for a fresh copy and the wizard works', async () => {
      const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 }, extraHTTPHeaders: { Via: '1.1 av-gateway', 'X-Forwarded-For': '127.0.0.1', 'X-Forwarded-Proto': 'http' } });
      try {
        const page = await ctx.newPage();
        let stale = 0; let fresh = 0;
        await page.route((u) => u.pathname === '/config.js', (route) => {
          const u = new URL(route.request().url());
          if (u.searchParams.has('v')) { stale++; return route.fulfill({ status: 200, contentType: 'application/javascript', body: STALE_CONFIG_JS }); }
          if (u.searchParams.has('fresh')) fresh++;
          return route.continue();
        });
        const r = await runWizard(page, { email: 'owner3@rsf.test', shots, shot: 'S3-preview.png' });
        if (!stale) throw new Error('the stale answer was never served (the shell is not versioned?)');
        if (r.cfg.secret) throw new Error('the page had the secret from the start — the stale copy was not used, nothing was tested');
        if (fresh < 1) throw new Error('the ERP never asked for a fresh /config.js');
        if (!r.reached) throw new Error(`no preview; error "${r.error}"; page "${r.pageText}"`);
        evidence.S3 = { stale, fresh, ...r };
        return `stale copy served ${stale}×, fresh copy fetched ${fresh}× by the page; the local product's headers did not matter; preview reached: ${r.preview.slice(0, 90)}…`;
      } finally { await ctx.close(); }
    });
    await R.check('S3b the installer\'s log says why the admin bits were (or were not) withheld — names of headers, never values', async () => {
      const log = hb();
      // a request that WAS withheld for a reason: run it once so there is a line to read
      await get(`${UI}/config.js`, { host: 'localhost:47395', 'cf-ray': 'RAYVALUE-123', 'x-forwarded-for': '203.0.113.9' });
      await sleep(500);
      const after = hb();
      const m = after.split('\n').filter((l) => /\[config\.js\] admin bits WITHHELD/.test(l));
      if (!m.length) throw new Error('no "admin bits WITHHELD" line in heartbeat.log');
      const line = m[m.length - 1];
      if (!/cloudflare-header\(cf-ray\)/.test(line) || !/x-forwarded-for:foreign-address/.test(line) || !/proxyHeaders=\[[^\]]*cf-ray/.test(line)) throw new Error(`line lacks the reasons / header names: ${line}`);
      if (/RAYVALUE-123|203\.0\.113\.9/.test(after)) throw new Error('a header VALUE reached the log');
      const before = m.length;
      for (let i = 0; i < 5; i++) await get(`${UI}/config.js`, { host: 'localhost:47395', 'cf-ray': 'RAYVALUE-123', 'x-forwarded-for': '203.0.113.9' });
      const again = hb().split('\n').filter((l) => /admin bits WITHHELD \(cloudflare-header\(cf-ray\), x-forwarded-for:foreign-address\)/.test(l));
      if (again.length !== 1) throw new Error(`the same reason was logged ${again.length}× (rate limit)`);
      return `"${line.replace(/^\[[^\]]+\]\s*/, '').slice(0, 220)}"; the same reason is logged once`;
    });

    // ── S4: tunnel-shaped ──
    await R.check('S4 tunnel-shaped requests (Cf-Ray, Cf-Connecting-Ip, Cdn-Loop, a foreign X-Forwarded-For) get NO admin bits, and the wizard shows the FRIENDLY localized text, never developer words', async () => {
      const tunnel = { 'Cf-Ray': '8a1b2c3d4e5f-FRA', 'Cf-Connecting-Ip': '203.0.113.9', 'Cdn-Loop': 'cloudflare; loops=1', 'X-Forwarded-For': '203.0.113.9', 'X-Forwarded-Proto': 'https' };
      const direct = await get(`${UI}/config.js`, tunnel);
      if (/localApiSecret/.test(direct.body)) throw new Error('a tunnel-shaped request received the admin secret');
      const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 }, extraHTTPHeaders: tunnel });
      try {
        const page = await ctx.newPage();
        const r = await runWizard(page, { email: 'owner4@rsf.test', expectFailure: true, shots, shot: 'S4-friendly.png' });
        if (r.reached) throw new Error('the wizard got through on a tunnel-shaped page');
        const text = await page.evaluate(() => document.body.innerText);
        if (DEV_TEXT_RE.test(text)) throw new Error(`developer text on the page: ${text.match(DEV_TEXT_RE)[0]}`);
        if (!FRIENDLY_RE.test(text)) throw new Error(`no friendly message; error "${r.error}"; page "${text.slice(0, 300)}"`);
        evidence.S4 = { error: r.error };
        return `no admin bits for tunnel headers; the wizard says: "${(text.match(FRIENDLY_RE) || [''])[0]}…"`;
      } finally { await ctx.close(); }
    });
  } finally {
    await browser.close().catch(() => {});
    await stopApp(child, userData);
  }
  fs.writeFileSync(path.join(WORK, 'results.json'), JSON.stringify({ at: new Date().toISOString(), app: APP || 'dev checkout', rsf: path.basename(RSF), summary: R.summary(), rows: R.rows, evidence }, null, 2));
  console.log(`\nrsf-wizard-ui-check: ${R.summary()}  →  ${WORK}/results.json`);
  process.exit(R.failed.length ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(1); });
