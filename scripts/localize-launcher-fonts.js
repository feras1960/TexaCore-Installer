#!/usr/bin/env node
'use strict';
// localize-launcher-fonts — the launcher window must not need the internet for its font (2.0.5 final).
// RC1/RC2 linked Cairo from fonts.googleapis.com: offline, the window fell back to the system Arabic face. This copies the Cairo woff2 files the window uses
// (Arabic + Latin + Latin-ext, weights 400/500/600/700; Cairo has no Cyrillic, so ru / uk use the system sans) from the @fontsource/cairo devDependency into
// src/fonts/ and writes src/fonts/fonts.css (the @font-face rules, relative urls). The OUTPUT IS COMMITTED (OFL 1.1, ~170 KB), so a build needs no node_modules for it;
// re-run only to refresh.   node scripts/localize-launcher-fonts.js
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const SRC_DIR = path.join(ROOT, 'node_modules', '@fontsource', 'cairo');
const OUT = path.join(ROOT, 'src', 'fonts');
const WEIGHTS = [400, 500, 600, 700];
const SUBSETS = ['arabic', 'latin-ext', 'latin'];
fs.mkdirSync(OUT, { recursive: true });
const css = ['/* Generated by scripts/localize-launcher-fonts.js from @fontsource/cairo (SIL Open Font License 1.1, see THIRD_PARTY_NOTICES.md). Do not edit. */'];
for (const w of WEIGHTS) {
  const text = fs.readFileSync(path.join(SRC_DIR, `${w}.css`), 'utf8');
  for (const sub of SUBSETS) {
    const m = new RegExp(`/\\*\\s*cairo-${sub}-${w}-normal\\s*\\*/\\s*@font-face\\s*\\{[^}]*?unicode-range:\\s*([^;]+);`).exec(text);
    if (!m) throw new Error(`no ${sub} ${w} block in @fontsource/cairo/${w}.css`);
    const file = `cairo-${sub}-${w}-normal.woff2`;
    fs.copyFileSync(path.join(SRC_DIR, 'files', file), path.join(OUT, file));
    css.push(`@font-face { font-family: 'Cairo'; font-style: normal; font-display: swap; font-weight: ${w}; src: url('${file}') format('woff2'); unicode-range: ${m[1].trim()}; }`);
  }
}
fs.writeFileSync(path.join(OUT, 'fonts.css'), css.join('\n') + '\n');
console.log(`launcher fonts: ${WEIGHTS.length * SUBSETS.length} woff2 files + fonts.css → src/fonts`);
