#!/usr/bin/env node
'use strict';
// ════════════════════════════════════════════════════════════════
// pack-baseline — build step (runs before electron-builder, see package.json): turn the plain baseline files and the installer-owned
// SQL into ONE encrypted container, generate its key module, and stage what the package will carry.
//
//   node scripts/pack-baseline.js
//
//   in : baseline/{production_baseline.sql, production_baseline.inventory.json, storage_stubs.sql, [reference_data.sql]} (verified against the pin)
//        src/bootstrap/{local_extras.sql, reference_seed.sql}
//   out: build/baseline-pack/{baseline.bin, PACKED.json, BASELINE_PIN.json}   ← package.json extraResources "baseline" comes from here
//        src/baseline-key.generated.js                                        ← the key, as random fragments + a derivation (git-ignored;
//                                                                              afterPack obfuscates it together with the rest of the app code)
// A new random key every build. Nothing here is committed.
// ════════════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { pack, unpack, sha256 } = require('../src/baseline-pack');
const bootstrap = require('../src/bootstrap');

const ROOT = path.join(__dirname, '..');
const BASELINE = path.join(ROOT, 'baseline');
const BOOT = path.join(ROOT, 'src', 'bootstrap');
const OUT = path.join(ROOT, 'build', 'baseline-pack');
const KEY_FILE = path.join(ROOT, 'src', 'baseline-key.generated.js');

function writeKeyModule() {
  const frag = () => crypto.randomBytes(32).toString('hex');
  const src = `'use strict';
// GENERATED by scripts/pack-baseline.js for ONE build — never committed.
const crypto = require('crypto');
const parts = ['${frag()}', '${frag()}', '${frag()}', '${frag()}'];
module.exports = function key() {
  const b = parts.map((h) => Buffer.from(h, 'hex'));
  const x = Buffer.alloc(32);
  for (let i = 0; i < 32; i++) x[i] = (b[0][i] ^ (((b[1][i] << 3) | (b[1][i] >> 5)) & 255) ^ ((b[2][(i * 11 + 5) % 32] + i) & 255) ^ b[3][31 - i]) & 255;
  return crypto.createHmac('sha256', x).update('texacore.baseline.container.v1').digest();
};
`;
  fs.writeFileSync(KEY_FILE, src, { mode: 0o600 });
  delete require.cache[require.resolve(KEY_FILE)];
  return require(KEY_FILE)();
}

function main() {
  const problems = bootstrap.verifyBaselineFiles(BASELINE);
  if (problems.length) { console.error(`pack-baseline: the plain baseline does not match its pin — ${problems.join('; ')}\n  run: node scripts/sync-baseline.js --erp <ERP checkout>`); process.exit(1); }
  const pin = bootstrap.loadPin(BASELINE);
  const defects = require('./sync-baseline').baselineProblems(fs.readFileSync(path.join(BASELINE, 'production_baseline.sql'), 'utf8'));
  if (defects.length) { console.error(`pack-baseline: the baseline is defective — ${defects.join('; ')}`); process.exit(1); }
  const entries = [];
  for (const name of ['production_baseline.sql', 'production_baseline.inventory.json', 'storage_stubs.sql', 'reference_data.sql']) {
    const f = path.join(BASELINE, name);
    if (fs.existsSync(f)) entries.push({ name, data: fs.readFileSync(f) });
    else if (name !== 'reference_data.sql') { console.error(`pack-baseline: ${name} is missing`); process.exit(1); }
  }
  for (const name of ['local_extras.sql', 'reference_seed.sql']) entries.push({ name, data: fs.readFileSync(path.join(BOOT, name)) });
  for (const [name, meta] of Object.entries(pin.files)) {
    const e = entries.find((x) => x.name === name);
    if (!e || sha256(e.data) !== meta.sha256) { console.error(`pack-baseline: ${name} is not what the pin says`); process.exit(1); }
  }
  const key = writeKeyModule();
  const blob = pack(entries, key);
  // self-test with the key module exactly as the packaged code will load it
  delete require.cache[require.resolve(KEY_FILE)];
  const back = unpack(blob, require(KEY_FILE)());
  for (const e of entries) if (!back.get(e.name) || !back.get(e.name).equals(e.data)) { console.error(`pack-baseline: self-test failed for ${e.name}`); process.exit(1); }

  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(path.join(OUT, 'baseline.bin'), blob);
  fs.copyFileSync(path.join(BASELINE, 'BASELINE_PIN.json'), path.join(OUT, 'BASELINE_PIN.json'));
  fs.writeFileSync(path.join(OUT, 'PACKED.json'), JSON.stringify({
    format: 'TXB1', blobBytes: blob.length, blobSha256: sha256(blob), createdAt: new Date().toISOString(),
    entries: entries.map((e) => ({ name: e.name, bytes: e.data.length })),
  }, null, 2) + '\n');
  const plainBytes = entries.reduce((n, e) => n + e.data.length, 0);
  console.log(`pack-baseline: ${entries.length} files (${(plainBytes / 1e6).toFixed(1)} MB) → baseline.bin ${(blob.length / 1e6).toFixed(1)} MB (gzip + AES-256-GCM), key module written (git-ignored)`);
}
main();
