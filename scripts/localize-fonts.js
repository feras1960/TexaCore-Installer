#!/usr/bin/env node
'use strict';
// ════════════════════════════════════════════════════════════════
// localize-fonts — the web UI must not need the internet for its fonts.
//
// The ERP's index.html loads Cairo / Tajawal / Inter / JetBrains Mono from fonts.googleapis.com; on an offline desktop the
// app then falls back to system fonts (Arabic text in the wrong face, layout shifts). This step, run on the synced
// ./frontend (scripts/sync-frontend.js), copies the needed woff2 files from the @fontsource packages (devDependencies),
// writes frontend/fonts/fonts.css, and rewrites index.html to use it. Only the weights/subsets the UI uses are copied
// (≈1 MB): Arabic + Latin for the Arabic faces, Latin + Latin-ext + Cyrillic for Inter (the UI ships ru/uk), Latin + Cyrillic mono.
//
//   node scripts/localize-fonts.js [frontendDir]      REQUIRE_LOCAL_FONTS=1 → any missing file or leftover remote reference FAILS
// ════════════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SPEC = [
  { pkg: 'cairo', weights: [400, 500, 600, 700, 800, 900], subsets: ['arabic', 'latin', 'latin-ext'] },
  { pkg: 'tajawal', weights: [300, 400, 500, 700, 800], subsets: ['arabic', 'latin'] },
  { pkg: 'inter', weights: [300, 400, 500, 600, 700, 800], subsets: ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext'] },
  { pkg: 'jetbrains-mono', weights: [400, 500, 600], subsets: ['latin', 'cyrillic'] },
];
const REMOTE = /fonts\.(?:googleapis|gstatic)\.com/;

function localize(frontendDir, { require: mustHave = false, log = console.log } = {}) {
  const outDir = path.join(frontendDir, 'fonts');
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  const css = ['/* Generated by scripts/localize-fonts.js from @fontsource — do not edit. */'];
  let files = 0;
  let bytes = 0;
  const missing = [];
  for (const { pkg, weights, subsets } of SPEC) {
    const dir = path.join(ROOT, 'node_modules', '@fontsource', pkg);
    for (const w of weights) {
      const cssFile = path.join(dir, `${w}.css`);
      if (!fs.existsSync(cssFile)) { missing.push(`@fontsource/${pkg}/${w}.css`); continue; }
      const text = fs.readFileSync(cssFile, 'utf8');
      for (const m of text.matchAll(/\/\*\s*([a-z0-9-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)) {
        const label = m[1];                              // e.g. cairo-arabic-400-normal
        const subset = label.replace(new RegExp(`^${pkg}-`), '').replace(new RegExp(`-${w}-normal$`), '');
        if (!subsets.includes(subset)) continue;
        const wf = /url\(\.\/files\/([^)]+\.woff2)\)\s*format\('woff2'\)/.exec(m[2]);
        if (!wf) { missing.push(`${label}: no woff2 source`); continue; }
        const src = path.join(dir, 'files', wf[1]);
        if (!fs.existsSync(src)) { missing.push(path.relative(ROOT, src)); continue; }
        fs.copyFileSync(src, path.join(outDir, wf[1]));
        files += 1; bytes += fs.statSync(src).size;
        const block = m[2].replace(/src:\s*url\([^;]*;/, `src: url(./${wf[1]}) format('woff2');`);
        css.push(`/* ${label} */\n${block}`);
      }
    }
  }
  if (missing.length && mustHave) throw new Error(`REQUIRE_LOCAL_FONTS: ${missing.length} font file(s) missing: ${missing.slice(0, 5).join(', ')}`);
  fs.writeFileSync(path.join(outDir, 'fonts.css'), css.join('\n') + '\n');

  // index.html: drop the Google links, add the local stylesheet
  const indexPath = path.join(frontendDir, 'index.html');
  let html = fs.readFileSync(indexPath, 'utf8');
  html = html.replace(/\s*<link[^>]+href="https:\/\/fonts\.(?:googleapis|gstatic)\.com[^"]*"[^>]*>\s*/g, '\n    ');
  if (!/href="\/fonts\/fonts\.css"/.test(html)) html = html.replace('</head>', '    <link rel="stylesheet" href="/fonts/fonts.css">\n  </head>');
  fs.writeFileSync(indexPath, html);

  // any remote font reference left in the shell or the stylesheets?
  const leftovers = [];
  const scan = (f) => { if (REMOTE.test(fs.readFileSync(f, 'utf8'))) leftovers.push(path.relative(frontendDir, f)); };
  scan(indexPath);
  const assets = path.join(frontendDir, 'assets');
  if (fs.existsSync(assets)) for (const f of fs.readdirSync(assets)) if (f.endsWith('.css')) scan(path.join(assets, f));
  if (leftovers.length && mustHave) throw new Error(`REQUIRE_LOCAL_FONTS: remote font reference(s) remain in ${leftovers.join(', ')}`);
  log(`  fonts: ${files} woff2 files, ${(bytes / 1024).toFixed(0)} KB → ${path.relative(ROOT, outDir) || outDir}${leftovers.length ? `  (remote refs left in: ${leftovers.join(', ')})` : ''}`);
  return { files, bytes, missing, leftovers };
}

module.exports = { localize, SPEC };

if (require.main === module) {
  const dir = path.resolve(process.argv[2] || path.join(ROOT, 'frontend'));
  try {
    localize(dir, { require: process.env.REQUIRE_LOCAL_FONTS === '1' });
  } catch (e) { console.error(e.message); process.exit(1); }
}
